// > Data Types
// Primitive Data Type      : String, Number, Boolean, Undefined, Null
// Non-Primitive Data Type  : Array & Object

// 1. String    : Segala sesuatu yang diapit dengan petik ('', "", ``)
let name = 'Defryan';
let address = 'Bogor';
let hobby = `Futsal`;
console.log(typeof name);
console.log(typeof address);
console.log(typeof hobby);
let discount = '10';
console.log(typeof discount);

// 2. Number
let point = 100;
console.log(typeof point);
let float = 9.5;
console.log(typeof float);

// 3. Boolean   : Bernilai true atau false
let isMarried = true;
let isGraduated = false;
console.log(typeof isMarried);
console.log(typeof isGraduated);

// 4. Undefined & Null
let courseName;
let studentName = null;
console.log(typeof courseName);
console.log(typeof studentName);
