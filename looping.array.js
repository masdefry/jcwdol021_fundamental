// > LOOPING ARRAY;

const products = [
  'Smartphone',
  'Laptop',
  'Tablet',
  'Smartwatch',
  'Headphones',
  'Camera',
  'Speaker',
];
for (let i = 0; i < products.length; i++) {
  console.log(products[i]);
}

// For of Loop : Melooping seluruh item/element di dalam array
const fruits = ['Apple', 'Banana', 'Cherry', 'Date', 'Elderberry'];
for (const fruit of fruits) {
  console.log(fruit);
};

